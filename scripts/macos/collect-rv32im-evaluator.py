#!/usr/bin/env python3
"""Collect every evaluator attempt and identify source-bound final-candidate checks."""
import json
from pathlib import Path
import sys
from worker_provenance import ROOT, sha, verify_build


def main():
    if len(sys.argv)!=2:raise SystemExit('usage: collect-rv32im-evaluator.py ENGINE')
    engine=Path(sys.argv[1]).resolve();base=ROOT/'target/macos/rv32im-metal'
    build=json.loads((base/'build.json').read_text())
    for name,digest in build['source']['inputs'].items():assert sha(Path(name))==digest
    binary=base/'build/release/hemi-macos-rv32im-metal-prototype'
    assert sha(binary)==build['binary_sha256']
    worker=verify_build('native-recursion-metal',engine)
    report={'schema_version':1,'status':'completed','build':build,'collector_sha256':sha(Path(__file__)),
        'generated_source':json.loads((base/'evaluator.json').read_text()),
        'verified_worker_binary_sha256':worker['binary_sha256'],'attempts':[],
        'final_candidate_cases':[],'full_domain_cases':[]}
    for path in sorted((base/'runs').glob('*/result.json'),key=lambda p:p.stat().st_mtime):
        raw=json.loads(path.read_text());directory=path.parent
        for name,digest in raw['artifact_hashes'].items():assert sha(directory/name)==digest
        final=raw['build']==build
        phases=[json.loads(line) for line in (directory/'stdout.jsonl').read_text().splitlines()]
        cases=[p['data'] for p in phases if p['phase']=='case_complete']
        if raw['status']=='passed' and raw['command'][2]!='compile':assert cases
        failure=(directory/'stderr.log').read_text()
        error_lines=[line for line in failure.splitlines() if 'error:' in line or line.startswith('Error:')
            or 'panicked at' in line or line.startswith('assertion ') or line.strip().startswith(('left:','right:'))]
        row={'run':str(directory),'result_sha256':sha(path),'status':raw['status'],
            'source_matches_final_candidate':final,'command':raw['command'],
            'threads_per_threadgroup':raw.get('threads_per_threadgroup'),
            'binary_sha256':raw['build']['binary_sha256'],
            'shader_sha256':raw['build']['source']['inputs'][str(base/'evaluator.metal')],
            'elapsed_seconds':raw['elapsed_seconds'],
            'failure_excerpt':'\n'.join(error_lines)[:8000] if raw['status']!='passed' else None,
            'failure_log_bytes':(directory/'stderr.log').stat().st_size,
            'failure_diagnostics':[p['data'] for p in phases if p['phase']=='comparison_failed'],
            'compilation':[p for p in phases if p['phase']=='compiled'],
            'cases':cases,'artifact_hashes':raw['artifact_hashes']}
        report['attempts'].append(row)
        if final and raw['status']=='passed':
            assert raw['verified_worker_build']==worker
            for case in cases:
                assert case['status']=='matched' and case['reuse_matched'] and case['completed_dispatches']==2
                assert case['inputs_unchanged'] and case['guards_preserved']
                assert case['compared_field_elements']==case['domain']*4
                assert case['command']['status']==case['reuse_command']['status']=='Completed'
                assert case['command']['threads_per_threadgroup']==case['reuse_command']['threads_per_threadgroup']==32
                item={'run':str(directory),'result_sha256':sha(path),**case}
                report['final_candidate_cases'].append(item)
                if case['po2']==20:report['full_domain_cases'].append(item)
    cases=report['final_candidate_cases'];full=report['full_domain_cases']
    assert {4,8,14,18,20}<={case['po2'] for case in cases}
    assert len(full)>=2 and len({c['seed'] for c in full})>=2
    report['totals']={'attempts':len(report['attempts']),
        'failed_attempts':sum(r['status']!='passed' for r in report['attempts']),
        'final_candidate_cases':len(cases),'full_domain_cases':len(full),
        'final_candidate_completed_dispatches':sum(c['completed_dispatches'] for c in cases),
        'compared_field_elements_including_reuse':sum(c['compared_field_elements']*c['completed_dispatches'] for c in cases)}
    report['decision']='Isolated evaluator feasibility passes; proceed to shared-buffer circuit adapter and whole-proof validation. No full-port or complete-throughput acceptance yet.'
    for name in ['final-state.json','archive/candidate/manifest.json']:
        path=base/name
        report[name]={'path':str(path),'sha256':sha(path),'contents':json.loads(path.read_text())}
    assert not report['final-state.json']['contents']['proof_or_evaluator_processes']
    report['limitations']=[
        'Synthetic field matrices; no valid RV32IM witness or complete proof is generated by this harness.',
        'Isolated CPU/Metal evaluation observations with fixed ordering, not a counterbalanced whole-proof benchmark.',
        'GPU dispatch includes command submission/completion; pipeline compiled before timing. Reuse dispatch follows CPU comparison.',
        'Physical footprint uses proc_pid_rusage RUSAGE_INFO_V4. Driver compiler services are outside this process; host availability is guarded.',
        'The four-entry normalization table is checked against modular-u64 arithmetic; every output is compared to CPU per-cycle normalization.',
        'The earlier divergent-normalization mismatch mechanism is unconfirmed; retain the failing observations and do not reuse that wrapper.',
        'The 1024-thread failure is a confirmed Metal out-of-memory error. Retain 32 threads; do not adopt the HAL maximum automatically.',
        'No verifier, control IDs, proof format, worker implementation or engine source changed.']
    output=ROOT/'docs/macos/evidence/rv32im-evaluator-prototype.json'
    output.write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps({'totals':report['totals'],'full_domain_cases':full},indent=2))


if __name__=='__main__':main()
